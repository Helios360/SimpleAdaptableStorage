  <h1>Mentions légales</h1>
  <p>Cette plateforme collecte et stocke des données à caractère personnel pour le compte d'un organisme de formation. Les responsables du traitement sont l'organisme ainsi que ses partenaires habilités.</p>

  <h2>Données collectées</h2>
  <ul>
    <li>Identité, coordonnées (email, téléphone, adresse)</li>
    <li>Date de naissance, mobilité, permis, véhicule</li>
    <li>CV et pièces d'identité (stockés chiffrés, accès restreint)</li>
    <li>Résultats des tests de compétences</li>
  </ul>

  <h2>Conservation</h2>
  <p>Les données sont conservées le temps strictement nécessaire au suivi du candidat. Vous pouvez demander la suppression de votre compte depuis votre profil ou par email.</p>

  <h2>Droits</h2>
  <p>Conformément au RGPD, vous disposez d'un droit d'accès, de rectification, d'opposition et d'effacement.</p>
